#ifndef _RETRO_FONT_H_
#define _RETRO_FONT_H_

//////////////////////////////////////////////////////////////////////////////////////

#include <stdint.h>

//////////////////////////////////////////////////////////////////////////////////////

typedef struct _font_data_t
{
	uint16_t width;
	uint16_t height;
	uint16_t offset;
	uint16_t size;
    uint8_t type;

	const uint8_t * data;

} font_data_t;

//////////////////////////////////////////////////////////////////////////////////////

enum
{
    // mono fonts
	FONT_4x6,
	FONT_5x12,
	FONT_6x8,
	FONT_8x8,
	FONT_10x18,
	FONT_12x16,

    // colour fonts
    FONT_C8x14,
    FONT_C12x20,
};

//////////////////////////////////////////////////////////////////////////////////////

extern const font_data_t font_c8x14;
extern const font_data_t font_c12x20;

//////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////

//////////////////////////////////////////////////////////////////////////////////////

#endif // _RETRO_FONT_H_
