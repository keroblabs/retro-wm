#!/usr/bin/env python3
"""Convert a PNG character grid to a C font_data_t with 4-bit grayscale pixels.

Requires Pillow. Coordinates are zero-based. Glyphs are read left to right,
then top to bottom. The darkest and lightest pixels across the extracted
glyphs become 0 and 15, with linear, rounded quantization between them.
Each row starts on a byte boundary; its leftmost pixel is in bits [3:0].
"""

import argparse
from pathlib import Path

from PIL import Image


def pack_glyph(pixels: bytes, width: int, height: int) -> bytes:
    """Pack normalized pixels, padding an odd row's unused high nibble with 0."""
    packed = bytearray()
    for y in range(height):
        row = pixels[y * width:(y + 1) * width]
        for x in range(0, width, 2):
            right = row[x + 1] if x + 1 < width else 0
            packed.append(row[x] | (right << 4))
    return bytes(packed)


def convert_font(
    source: Path,
    output: Path,
    *,
    origin: tuple[int, int],
    cell: tuple[int, int],
    crop: tuple[int, int, int, int],
    columns: int = 8,
    rows: int = 12,
    first_character: int = 0x20,
) -> None:
    """Extract, normalize and pack the grid, then write its C definition."""
    start_x, start_y = origin
    cell_width, cell_height = cell
    offset_x, offset_y, width, height = crop
    if min(start_x, start_y, offset_x, offset_y) < 0:
        raise ValueError("Origin and crop offsets must be nonnegative")
    if min(cell_width, cell_height, width, height, columns, rows) <= 0:
        raise ValueError("Cell, crop and grid dimensions must be positive")
    if offset_x + width > cell_width or offset_y + height > cell_height:
        raise ValueError("The extraction crop must fit inside each character cell")
    size = ((width + 1) // 2) * height
    if max(width, height, size) > 0xFFFF:
        raise ValueError("Font dimensions and byte size must fit uint16_t")
    if first_character < 0 or first_character + columns * rows > 0x10000:
        raise ValueError("Character codes must fit uint16_t")
    if source.resolve() == output.resolve():
        raise ValueError("Input PNG and output C file must be different paths")

    with Image.open(source) as image:
        if image.format != "PNG":
            raise ValueError("Input must be a PNG image")
        right = start_x + (columns - 1) * cell_width + offset_x + width
        bottom = start_y + (rows - 1) * cell_height + offset_y + height
        if right > image.width or bottom > image.height:
            raise ValueError(
                f"Extraction grid ends at ({right}, {bottom}), "
                f"outside the {image.width}x{image.height} image"
            )
        # Alpha is composited onto black before calculating luminance.
        background = Image.new("RGBA", image.size, (0, 0, 0, 255))
        grayscale = Image.alpha_composite(background, image.convert("RGBA")).convert("L")

    glyphs = []
    for row in range(rows):
        for column in range(columns):
            left = start_x + column * cell_width + offset_x
            top = start_y + row * cell_height + offset_y
            glyphs.append(grayscale.crop((left, top, left + width, top + height)))

    extrema = [glyph.getextrema() for glyph in glyphs]
    darkest = min(low for low, _ in extrema)
    lightest = max(high for _, high in extrema)
    span = lightest - darkest
    # A constant image has no contrast and becomes an empty font.
    levels = [
        max(0, min(15, ((value - darkest) * 15 + span // 2) // span))
        if span else 0
        for value in range(256)
    ]
    packed = [
        pack_glyph(glyph.point(levels).tobytes(), width, height)
        for glyph in glyphs
    ]

    name = f"c{width}x{height}"
    lines = [
        "/* Generated by tools/convert_font.py; do not edit.",
        f" * Grid origin: ({start_x}, {start_y}); cell: {cell_width}x{cell_height}.",
        f" * Crop: ({offset_x}, {offset_y}), {width}x{height}; grid: {columns}x{rows}.",
        f" * Luminance {darkest}..{lightest} normalized to 0..15 across all glyphs.",
        " * Rows run top to bottom; the left pixel occupies bits [3:0].",
        " */",
        "",
        '#include "retro_font.h"',
        "",
        f"static const uint8_t char_map_{name}[] = {{",
    ]
    for index, data in enumerate(packed):
        code = first_character + index
        label = f" {chr(code)!r}" if 0x20 <= code <= 0x7E else ""
        lines.append(f"    /* Character 0x{code:02X}{label} */")
        for start in range(0, len(data), 16):
            lines.append("    " + ", ".join(f"0x{byte:02X}" for byte in data[start:start + 16]) + ",")
    lines.extend([
        "};",
        "",
        f"const font_data_t font_{name} =",
        "{",
        f"    {width},\t\t// width",
        f"    {height},\t\t// height",
        f"    0x{first_character:02X},\t// first character",
        f"    {size},\t\t// bytes per glyph",
        f"    FONT_C{width}x{height},\t// font enum",
        f"    char_map_{name}",
        "};",
        "",
    ])
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="input PNG character grid")
    parser.add_argument("output", type=Path, help="output C source file")
    parser.add_argument("--origin", type=int, nargs=2, required=True,
                        metavar=("X", "Y"), help="top-left corner of the first character cell")
    parser.add_argument("--cell", type=int, nargs=2, required=True,
                        metavar=("WIDTH", "HEIGHT"), help="character cell spacing")
    parser.add_argument("--crop", type=int, nargs=4, required=True,
                        metavar=("X", "Y", "WIDTH", "HEIGHT"),
                        help="extraction rectangle relative to each character cell")
    parser.add_argument("--columns", type=int, default=8, help="characters per grid row (default: 8)")
    parser.add_argument("--rows", type=int, default=12, help="grid rows (default: 12)")
    parser.add_argument("--first-character", type=lambda value: int(value, 0), default=0x20,
                        help="first character code in decimal or hex (default: 0x20)")
    args = parser.parse_args()
    try:
        convert_font(
            args.source, args.output,
            origin=tuple(args.origin), cell=tuple(args.cell), crop=tuple(args.crop),
            columns=args.columns, rows=args.rows, first_character=args.first_character,
        )
    except (OSError, ValueError) as error:
        parser.error(str(error))
    width, height = args.crop[2:]
    size = ((width + 1) // 2) * height
    print(f"Wrote {args.output}: {args.columns * args.rows} glyphs, "
          f"{width}x{height}, {size} bytes per glyph")


if __name__ == "__main__":
    main()
